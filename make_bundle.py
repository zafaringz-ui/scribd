#!/usr/bin/env python3
"""
make_bundle.py — build scribd_all.py, a single-file version of the tools.

The fragment engine imports `scribd_pdf`, which means two files have to sit next
to each other on the server.  Hosting panels make that annoying, so this packs
both modules into one uploadable file:

    python make_bundle.py            # writes ./scribd_all.py

`scribd_all.py` behaves exactly like `scribd_shot.py`:

    python scribd_all.py 272351848 -o output --engine fragment
"""

from __future__ import annotations

import base64
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHOT = HERE / "scribd_shot.py"
PDF = HERE / "scribd_pdf.py"
LAUNCH = HERE / "chromium_launch.py"
ENVFILE = HERE / "envfile.py"
DRIME = HERE / "drime.py"
LOGFMT = HERE / "logfmt.py"
OUT = HERE / "scribd_all.py"

HEADER = '''#!/usr/bin/env python3
# ruff: noqa: E402, F401, I001  (generated: two modules concatenated)
"""
scribd_all.py - single-file build of scribd_shot.py + its helpers.

Generated by make_bundle.py - edit the source files, not this one.

    python scribd_all.py <URL_OR_ID> [...] [-o OUTDIR]

The screenshot tool is appended verbatim below; the fragment engine needs helpers
from scribd_pdf, which are embedded here as a module named "scribd_pdf".
"""

from __future__ import annotations

import base64
import sys
import types

'''

SHIM = """
# logfmt first: chromium_launch and the engines import it on their first line
_logfmt_mod = types.ModuleType("logfmt")
_logfmt_mod.__dict__["__file__"] = __file__
sys.modules.setdefault("logfmt", _logfmt_mod)
exec(
    compile(
        base64.b64decode(_EMBEDDED_LOGFMT).decode("utf-8"),
        "logfmt.py",
        "exec",
    ),
    _logfmt_mod.__dict__,
)

_launch = types.ModuleType("chromium_launch")
_launch.__dict__["__file__"] = __file__
sys.modules.setdefault("chromium_launch", _launch)
exec(
    compile(
        base64.b64decode(_EMBEDDED_CHROMIUM_LAUNCH).decode("utf-8"),
        "chromium_launch.py",
        "exec",
    ),
    _launch.__dict__,
)

_env_mod = types.ModuleType("envfile")
_env_mod.__dict__["__file__"] = __file__
sys.modules.setdefault("envfile", _env_mod)
exec(
    compile(
        base64.b64decode(_EMBEDDED_ENVFILE).decode("utf-8"),
        "envfile.py",
        "exec",
    ),
    _env_mod.__dict__,
)

_drime_mod = types.ModuleType("drime")
_drime_mod.__dict__["__file__"] = __file__
sys.modules.setdefault("drime", _drime_mod)
exec(
    compile(
        base64.b64decode(_EMBEDDED_DRIME).decode("utf-8"),
        "drime.py",
        "exec",
    ),
    _drime_mod.__dict__,
)

_shim = types.ModuleType("scribd_pdf")
_shim.__dict__["__file__"] = __file__
# register before exec: dataclasses resolves cls.__module__ through sys.modules
sys.modules.setdefault("scribd_pdf", _shim)
exec(
    compile(
        base64.b64decode(_EMBEDDED_SCRIBD_PDF).decode("utf-8"),
        "scribd_pdf.py",
        "exec",
    ),
    _shim.__dict__,
)

"""


def main() -> int:
    for required in (SHOT, PDF, LAUNCH, ENVFILE, DRIME, LOGFMT):
        if not required.exists():
            print(f"missing source file: {required}")
            return 1

    pdf_src = PDF.read_text(encoding="utf-8")
    shot_src = SHOT.read_text(encoding="utf-8")
    # the bundle's own header carries the __future__ import
    shot_src = shot_src.replace("from __future__ import annotations\n", "", 1)

    blob = base64.b64encode(pdf_src.encode("utf-8")).decode("ascii")
    lines = "\n".join(f'    "{part}"' for part in textwrap.wrap(blob, 88))
    assignment = f"_EMBEDDED_SCRIBD_PDF = (\n{lines}\n)\n"

    launch_src = LAUNCH.read_text(encoding="utf-8")
    llines = "\n".join(
        f'    "{part}"'
        for part in textwrap.wrap(
            base64.b64encode(launch_src.encode("utf-8")).decode("ascii"), 88
        )
    )
    assignment += f"_EMBEDDED_CHROMIUM_LAUNCH = (\n{llines}\n)\n"

    for name, src in (
        ("_EMBEDDED_ENVFILE", ENVFILE),
        ("_EMBEDDED_DRIME", DRIME),
        ("_EMBEDDED_LOGFMT", LOGFMT),
    ):
        blob = base64.b64encode(src.read_bytes()).decode("ascii")
        body = "\n".join(f'    "{part}"' for part in textwrap.wrap(blob, 88))
        assignment += f"{name} = (\n{body}\n)\n"

    parts = [
        HEADER,
        assignment,
        SHIM,
        "# " + "-" * 76,
        "# scribd_shot.py",
        "# " + "-" * 76,
        shot_src,
    ]
    content = "\n".join(parts)
    OUT.write_text(content, encoding="utf-8")
    OUT.chmod(0o755)
    size_kb = OUT.stat().st_size / 1024
    print(
        f"wrote {OUT.name} ({size_kb:,.0f} KB) from "
        f"{SHOT.name} + {PDF.name} + {LAUNCH.name} + {ENVFILE.name} + "
        f"{DRIME.name} + {LOGFMT.name}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
